"""Validate native room views and emit the browser's authored geometry.

Coordinates are centered percentages of the complete source image. They do not
describe equirectangular UVs or cropped/outpainted artwork. The renderer must fit
the whole image and project targets into the same fitted rectangle.
"""
from pathlib import Path
import hashlib
import json

ROOT = Path(__file__).resolve().parents[1]
EXTRA_FIXTURES = {
    'wardnorth': {'windowLever', 'coldWindow0', 'coldWindow1', 'coldWindow2'},
    'laundry': {'stove'},
    'chapel': {'candles'},
    'powercontrol': {'markerGraffiti'},
    'stafflounge': {'television'},
}


def rect_valid(rect, label):
    assert len(rect) == 4, (label, rect)
    x, y, w, h = rect
    assert all(isinstance(n, (int, float)) for n in rect), (label, rect)
    assert 0 <= x <= 100 and 0 <= y <= 100 and 0 < w <= 100 and 0 < h <= 100, (label, rect)
    assert x - w / 2 >= -.01 and x + w / 2 <= 100.01, (label, rect)
    assert y - h / 2 >= -.01 and y + h / 2 <= 100.01, (label, rect)


def main():
    world = json.loads((ROOT / 'data/room_views.json').read_text())
    base = json.loads((ROOT / 'data/chapter1_scenes.json').read_text())
    catalog = {r['id']: r for r in json.loads((ROOT / 'data/rooms.json').read_text())['rooms']}
    assert set(world) == set(base) == set(catalog) and len(world) == 27
    digests = set()
    directed_doors = 0
    fixture_count = 0
    for room, entry in world.items():
        assert entry['reviewed'], f'Unreviewed room: {room}'
        assert set(entry['views']) == {'front', 'rear'}, room
        expected = {f['id'] for f in base[room]['fixtures']} | EXTRA_FIXTURES.get(room, set())
        assert set(entry['fixtures']) == expected, (room, set(entry['fixtures']) ^ expected)
        expected_doors = {d['id'] for d in catalog[room]['connections']}
        actual_doors = []
        for view, definition in entry['views'].items():
            assert definition['reviewed'], f'Unreviewed view: {room}/{view}'
            path = ROOT / definition['asset']
            assert path.is_file(), f'Missing room artwork: {path}'
            digest = hashlib.sha256(path.read_bytes()).hexdigest()
            assert digest not in digests, f'Reused room image: {room}/{view}'
            digests.add(digest)
            for door, rect in definition['doors'].items():
                rect_valid(rect, f'{room}/{view}/door:{door}')
                actual_doors.append(door)
                directed_doors += 1
        assert len(actual_doors) == len(set(actual_doors)), f'Door appears in both views: {room}'
        assert set(actual_doors) == expected_doors, (room, set(actual_doors) ^ expected_doors)
        for fixture, spec in entry['fixtures'].items():
            assert spec['reviewed'] and spec['view'] in entry['views'], (room, fixture)
            rect_valid(spec['rect'], f'{room}/{fixture}')
            for key in ['itemRect', 'actorRect']:
                if key in spec:
                    rect_valid(spec[key], f'{room}/{fixture}/{key}')
            if 'after' in spec:
                assert spec['after']['flag'], (room, fixture)
                rect_valid(spec['after']['rect'], f'{room}/{fixture}/after')
            fixture_count += 1
        assert len(entry['threat']) == 3 and all(0 < n <= 100 for n in entry['threat']), room
        if 'droppedLight' in entry:
            rect_valid(entry['droppedLight'], f'{room}/droppedLight')
    assert directed_doors == 54 and fixture_count == 162
    output = '/* Generated by tools/build_room_views.py from reviewed native room coordinates. */\n'
    output += 'window.WardRoomViews=' + json.dumps(world, separators=(',', ':')) + ';\n'
    (ROOT / 'js/room_views_data.js').write_text(output)
    print(f'PASS {len(digests)} unique native room views, {directed_doors} directed doors, {fixture_count} authored fixtures')


if __name__ == '__main__':
    main()
